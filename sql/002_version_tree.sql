-- Persistent SVN transactions and immutable tree representations.
BEGIN;

CREATE SEQUENCE IF NOT EXISTS pgfs.node_ids START 1;
CREATE SEQUENCE IF NOT EXISTS pgfs.copy_ids START 1;

ALTER TABLE pgfs.node_revisions ADD COLUMN IF NOT EXISTS owner_txn text COLLATE "C";
CREATE INDEX IF NOT EXISTS nodes_owner ON pgfs.node_revisions(repository_id, owner_txn);

CREATE TABLE IF NOT EXISTS pgfs.transactions (
    repository_id uuid NOT NULL REFERENCES pgfs.repositories,
    txn_id text COLLATE "C" NOT NULL,
    base_rev bigint NOT NULL,
    root_node_revision_id bigint NOT NULL,
    flags integer NOT NULL DEFAULT 0,
    state text NOT NULL DEFAULT 'active' CHECK (state IN ('active','committed','aborted')),
    committed_rev bigint,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    PRIMARY KEY (repository_id, txn_id),
    FOREIGN KEY (repository_id, base_rev) REFERENCES pgfs.revisions,
    FOREIGN KEY (repository_id, root_node_revision_id) REFERENCES pgfs.node_revisions(repository_id,node_revision_id),
    CHECK ((state = 'committed') = (committed_rev IS NOT NULL))
);
CREATE TABLE IF NOT EXISTS pgfs.transaction_properties (
    repository_id uuid NOT NULL,
    txn_id text COLLATE "C" NOT NULL,
    name text COLLATE "C" NOT NULL,
    value bytea NOT NULL,
    PRIMARY KEY (repository_id, txn_id, name),
    FOREIGN KEY (repository_id, txn_id) REFERENCES pgfs.transactions
);

CREATE TABLE IF NOT EXISTS pgfs.property_sets (
    properties_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repository_id uuid NOT NULL REFERENCES pgfs.repositories,
    UNIQUE (repository_id, properties_id)
);
CREATE TABLE IF NOT EXISTS pgfs.properties (
    repository_id uuid NOT NULL,
    properties_id bigint NOT NULL,
    name text COLLATE "C" NOT NULL,
    value bytea NOT NULL,
    PRIMARY KEY (repository_id, properties_id, name),
    FOREIGN KEY (repository_id, properties_id) REFERENCES pgfs.property_sets(repository_id,properties_id)
);

CREATE TABLE IF NOT EXISTS pgfs.directories (
    directory_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repository_id uuid NOT NULL REFERENCES pgfs.repositories,
    base_directory_id bigint,
    depth integer NOT NULL DEFAULT 0 CHECK (depth BETWEEN 0 AND 32),
    UNIQUE (repository_id, directory_id),
    FOREIGN KEY (repository_id, base_directory_id) REFERENCES pgfs.directories(repository_id,directory_id)
);
CREATE TABLE IF NOT EXISTS pgfs.directory_entries (
    repository_id uuid NOT NULL,
    directory_id bigint NOT NULL,
    name text COLLATE "C" NOT NULL CHECK (name <> '' AND position('/' IN name) = 0),
    child_node_revision_id bigint, -- NULL is an overlay tombstone.
    PRIMARY KEY (repository_id, directory_id, name),
    FOREIGN KEY (repository_id, directory_id) REFERENCES pgfs.directories(repository_id,directory_id),
    FOREIGN KEY (repository_id, child_node_revision_id) REFERENCES pgfs.node_revisions(repository_id,node_revision_id)
);

CREATE TABLE IF NOT EXISTS pgfs.contents (
    content_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repository_id uuid NOT NULL REFERENCES pgfs.repositories,
    owner_txn text COLLATE "C" NOT NULL,
    path text COLLATE "C" NOT NULL,
    length bigint NOT NULL DEFAULT 0 CHECK (length >= 0),
    md5 text COLLATE "C",
    sha1 text COLLATE "C",
    ready boolean NOT NULL DEFAULT false,
    abandoned boolean NOT NULL DEFAULT false,
    UNIQUE (repository_id, content_id),
    CHECK (NOT ready OR (length(md5) = 32 AND length(sha1) = 40))
);
CREATE TABLE IF NOT EXISTS pgfs.content_chunks (
    repository_id uuid NOT NULL,
    content_id bigint NOT NULL,
    chunk_number bigint NOT NULL CHECK (chunk_number >= 0),
    data bytea NOT NULL CHECK (octet_length(data) BETWEEN 1 AND 1048576),
    PRIMARY KEY (repository_id, content_id, chunk_number),
    FOREIGN KEY (repository_id, content_id) REFERENCES pgfs.contents(repository_id,content_id)
);

CREATE TABLE IF NOT EXISTS pgfs.transaction_changes (
    repository_id uuid NOT NULL,
    txn_id text COLLATE "C" NOT NULL,
    path text COLLATE "C" NOT NULL,
    node_revision_id bigint NOT NULL,
    change_kind text NOT NULL CHECK (change_kind IN ('add','modify','delete','replace')),
    node_kind text NOT NULL CHECK (node_kind IN ('file','dir')),
    text_mod boolean NOT NULL DEFAULT false,
    prop_mod boolean NOT NULL DEFAULT false,
    mergeinfo_mod boolean NOT NULL DEFAULT false,
    copyfrom_rev bigint,
    copyfrom_path text COLLATE "C",
    PRIMARY KEY (repository_id, txn_id, path),
    FOREIGN KEY (repository_id, txn_id) REFERENCES pgfs.transactions,
    FOREIGN KEY (repository_id, node_revision_id) REFERENCES pgfs.node_revisions(repository_id,node_revision_id),
    CHECK ((copyfrom_rev IS NULL) = (copyfrom_path IS NULL))
);
CREATE TABLE IF NOT EXISTS pgfs.revision_changes (
    repository_id uuid NOT NULL,
    rev bigint NOT NULL,
    path text COLLATE "C" NOT NULL,
    node_revision_id bigint NOT NULL,
    change_kind text NOT NULL CHECK (change_kind IN ('add','modify','delete','replace')),
    node_kind text NOT NULL CHECK (node_kind IN ('file','dir')),
    text_mod boolean NOT NULL,
    prop_mod boolean NOT NULL,
    mergeinfo_mod boolean NOT NULL,
    copyfrom_rev bigint,
    copyfrom_path text COLLATE "C",
    PRIMARY KEY (repository_id, rev, path),
    FOREIGN KEY (repository_id, rev) REFERENCES pgfs.revisions,
    FOREIGN KEY (repository_id, node_revision_id) REFERENCES pgfs.node_revisions(repository_id,node_revision_id),
    CHECK ((copyfrom_rev IS NULL) = (copyfrom_path IS NULL))
);

INSERT INTO pgfs.schema_versions(version) VALUES (2) ON CONFLICT DO NOTHING;
COMMIT;
