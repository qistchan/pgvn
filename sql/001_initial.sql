-- PgFS persistent repository records. PostgreSQL 18; migration version 1.
-- Revision numbers are allocated by locking repositories and incrementing HEAD,
-- not by a PostgreSQL sequence. Object identifiers may have gaps.
BEGIN;

CREATE SCHEMA IF NOT EXISTS pgfs;

CREATE TABLE IF NOT EXISTS pgfs.schema_versions (
    version integer PRIMARY KEY,
    installed_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

CREATE TABLE IF NOT EXISTS pgfs.repositories (
    repository_id uuid PRIMARY KEY,
    svn_uuid uuid NOT NULL,
    instance_id uuid NOT NULL,
    format_version integer NOT NULL CHECK (format_version = 1),
    head_rev bigint NOT NULL DEFAULT 0 CHECK (head_rev >= 0),
    created_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

CREATE TABLE IF NOT EXISTS pgfs.node_revisions (
    node_revision_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repository_id uuid NOT NULL REFERENCES pgfs.repositories(repository_id),
    node_id bigint NOT NULL,
    copy_id bigint NOT NULL DEFAULT 0,
    predecessor_id bigint,
    predecessor_count bigint NOT NULL DEFAULT 0,
    kind text NOT NULL CHECK (kind IN ('file', 'dir')),
    created_rev bigint NOT NULL,
    created_path text COLLATE "C" NOT NULL,
    copyfrom_rev bigint,
    copyfrom_path text COLLATE "C",
    content_id bigint,
    properties_id bigint,
    directory_id bigint,
    UNIQUE (repository_id, node_revision_id),
    FOREIGN KEY (repository_id, predecessor_id)
        REFERENCES pgfs.node_revisions(repository_id, node_revision_id),
    CHECK ((copyfrom_rev IS NULL) = (copyfrom_path IS NULL))
);

CREATE TABLE IF NOT EXISTS pgfs.revisions (
    repository_id uuid NOT NULL REFERENCES pgfs.repositories(repository_id),
    rev bigint NOT NULL CHECK (rev >= 0),
    root_node_revision_id bigint NOT NULL,
    origin_txn_id text COLLATE "C",
    PRIMARY KEY (repository_id, rev),
    UNIQUE (repository_id, origin_txn_id),
    FOREIGN KEY (repository_id, root_node_revision_id)
        REFERENCES pgfs.node_revisions(repository_id, node_revision_id)
);

CREATE TABLE IF NOT EXISTS pgfs.revision_properties (
    repository_id uuid NOT NULL,
    rev bigint NOT NULL,
    name text COLLATE "C" NOT NULL,
    value bytea NOT NULL,
    generation bigint NOT NULL DEFAULT 0,
    PRIMARY KEY (repository_id, rev, name),
    FOREIGN KEY (repository_id, rev)
        REFERENCES pgfs.revisions(repository_id, rev)
);

INSERT INTO pgfs.schema_versions(version) VALUES (1) ON CONFLICT DO NOTHING;
COMMIT;
